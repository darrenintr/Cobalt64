#!/usr/bin/env python3
"""Encode little-endian SPIR-V words independently of host byte order."""
from pathlib import Path
import struct

lines = ["// Generated by make shaders; see draw.vert and draw.frag."]
for stage in ("vert", "frag"):
    data = Path(f"draw.{stage}.spv").read_bytes()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    assert words[0] == 0x07230203
    lines.append(f"static const uint32_t {stage}_spv[] = {{")
    for start in range(0, len(words), 8):
        lines.append("    " + ",".join(f"0x{w:08x}u" for w in words[start:start+8]) + ",")
    lines.append("};")
Path("draw_spv.h").write_text("\n".join(lines) + "\n")
