"""Generate Navi33EmbeddedFirmware.cpp for the boot-time bring-up (Phase B1).

Embeds, as const byte arrays, the RX 7600 IP Discovery blob (built from
tests/fixtures/rx7600-linux-ipd.txt) and the ten linux-firmware files the
write stages pin: psp_13_0_7_sos.bin and the nine IP firmware files in the
order Navi33Psp13IpFw.h expects (tools/n33psp.c kIpFwFiles). Every file must
match its pinned SHA-256 (tests/fixtures/rx7600-fw-plan.tsv, Navi33Psp13Loader.h);
any mismatch refuses. The files come from --from DIR if given (plain .bin or
.bin.zst), otherwise from linux-firmware commit 1522c78a (20260915), first the
GitLab mirror, then git.kernel.org. AMD's linux-firmware licence (LICENSE.amdgpu)
allows redistribution in binary form.

Usage: tools/embed-firmware.py OUT.cpp [--from DIR]
"""
import hashlib
import pathlib
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
COMMIT = "1522c78a"
MIRRORS = ("https://gitlab.com/kernel-firmware/linux-firmware/-/raw/{c}/amdgpu/{n}.bin",
           "https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/amdgpu/{n}.bin?id={c}")
SOS = ("psp_13_0_7_sos", 248496, "94db505fa6482f258c33a0a8d412050f6d843ab4ada368252e988f82f8a26fa8")
IPFW_ORDER = ("gc_11_0_2_pfp", "gc_11_0_2_me", "gc_11_0_2_mec", "gc_11_0_2_rlc", "gc_11_0_2_imu",
              "sdma_6_0_2", "gc_11_0_2_mes_2", "gc_11_0_2_mes1", "smu_13_0_7")


def pins():
    out = {}
    for line in (ROOT / "tests/fixtures/rx7600-fw-plan.tsv").read_text().splitlines():
        f = line.split()
        if f and f[0] == "F":
            out[f[2]] = (int(f[3]), f[4])
    out[SOS[0]] = (SOS[1], SOS[2])
    return out


def load(name, src):
    if src:
        d = pathlib.Path(src)
        if (d / f"{name}.bin").exists():
            return (d / f"{name}.bin").read_bytes()
        z = d / f"{name}.bin.zst"
        if z.exists():
            return subprocess.run(["zstd", "-q", "-d", "-c", str(z)], check=True,
                                  capture_output=True).stdout
        raise SystemExit(f"embed-firmware: {name} not in {src}")
    for m in MIRRORS:
        try:
            with urllib.request.urlopen(m.format(c=COMMIT, n=name), timeout=60) as r:
                return r.read()
        except OSError as e:
            print(f"embed-firmware: {m.format(c=COMMIT, n=name)}: {e}", file=sys.stderr)
    raise SystemExit(f"embed-firmware: cannot fetch {name}")


def checked(name, data, pin):
    size, sha = pin
    got = hashlib.sha256(data).hexdigest()
    if len(data) != size or got != sha:
        raise SystemExit(f"embed-firmware: {name} is {len(data)} B {got}, pinned {size} B {sha}")
    return data


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return (f"alignas(16) const uint8_t {name}[{len(data)}]={{\n" + ",\n".join(rows) +
            f"}};\nconst size_t {name}Bytes={len(data)}u;\n")


def main(argv):
    if len(argv) not in (2, 4) or (len(argv) == 4 and argv[2] != "--from"):
        raise SystemExit(__doc__)
    src = argv[3] if len(argv) == 4 else None
    p = pins()
    sos = checked(SOS[0], load(SOS[0], src), p[SOS[0]])
    ipfw = b"".join(checked(n, load(n, src), p[n]) for n in IPFW_ORDER)
    out = pathlib.Path(argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    ipd = out.with_suffix(".ipd.bin")
    subprocess.run([sys.executable, "-I", str(ROOT / "tools/ipd-from-capture.py"),
                    str(ROOT / "tests/fixtures/rx7600-linux-ipd.txt"), str(ipd)],
                   check=True, capture_output=True)
    text = ("// Generated by tools/embed-firmware.py; do not edit. linux-firmware " + COMMIT +
            ", every file checked against its pinned SHA-256.\n"
            "#include \"Navi33EmbeddedFirmware.h\"\nnamespace navi33 { namespace embedded {\n" +
            array("kIpd", ipd.read_bytes()) + array("kSos", sos) + array("kIpFw", ipfw) + "} }\n")
    out.write_text(text)
    print(f"embed-firmware: wrote {out} (IPD {ipd.stat().st_size} B, sOS {len(sos)} B, IP firmware {len(ipfw)} B)")


if __name__ == "__main__":
    main(sys.argv)
